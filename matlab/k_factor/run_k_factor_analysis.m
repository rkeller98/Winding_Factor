function run_k_factor_analysis
% Standalone k-factor study, also called by the project-root entry point.
addpath(fullfile(fileparts(fileparts(mfilename('fullpath'))),'common'));
setup_matlab_paths('k_factor');
steps={@prepare_reduction_data,@analyze_winding_factors,@validate_winding_factor, ...
    @audit_reduction_sources,@analyze_flux_map_reduction,@plot_reduction_study};
descriptions={'Prepare measured-current/voltage flux data (Set1-3)', ...
    'Analyze conventional winding factors', ...
    'Evaluate local derivatives and analytic controls', ...
    'Audit historical FluxEval sources and coordinates', ...
    'Fit and compare coordinate reductions A-H', ...
    'Plot coordinate reduction study and write paper tables'};
for step=1:numel(steps)
    fprintf('\nk-factor [%d/%d]: %s\n',step,numel(steps),descriptions{step});
    feval(steps{step});
end
drawnow;
end
